export function getAccommodationById(id: string) {
  return ACCOMMODATIONS.find((a) => a.id === id);
}

export function filterAccommodations(filters: {
  destination?: string;
  type?: Accommodation["type"] | "ALL";
  guests?: number;
}) {
  const q = filters.destination?.trim().toLowerCase() ?? "";
  return ACCOMMODATIONS.filter((a) => {
    const matchType = !filters.type || filters.type === "ALL" || a.type === filters.type;
    const matchGuests = !filters.guests || a.capacity >= filters.guests;
    const matchQuery =
      !q ||
      a.city.toLowerCase().includes(q) ||
      a.district.toLowerCase().includes(q) ||
      a.country.toLowerCase().includes(q) ||
      a.name.toLowerCase().includes(q);
    return matchType && matchGuests && matchQuery;
  });
}
